"""Builds snow_leg/COMPARISON.md: original Leg Day leg vs snow leg, from the analysis outputs.
The original leg's numbers are read (never written) from ../analysis/out/gait.md and computed from
its STLs/slicer run (analysis/print_check.py writes both). Run after the other analyses.
"""
import json
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, ROOT)
sys.path.insert(0, HERE)
import params as P  # noqa: E402
import snowgeo as SG  # noqa: E402
from snow_model import sink, BEKKER, PRESTON  # noqa: E402
from mass_model import snow_groups, original_groups  # noqa: E402

ORIG_GAIT = os.path.abspath(os.path.join(ROOT, "..", "analysis", "out", "gait.md"))
G = P.G_ACC


def orig_gait():
    txt = open(ORIG_GAIT, encoding="utf-8").read()
    out = {}
    for gait in ("walk", "trot"):
        sec = txt.split(f"## {gait}:")[1].split("##")[0]
        m = re.search(r"ab/ad ([0-9.]+), hip ([0-9.]+), knee ([0-9.]+) Nm", sec)
        b = re.search(r"belt ≤ 60 N continuous \| [^|]+ \| ([0-9.]+) N", sec)
        sp = re.search(r"forward speed ([0-9.]+) m/s", txt.split(f"## {gait}:")[1])
        mass = re.search(r"Max robot mass for this gait: \*\*([0-9.]+) kg", sec)
        out[gait] = dict(abad=float(m.group(1)), hip=float(m.group(2)), knee=float(m.group(3)), belt=float(b.group(1)),
                         speed=float(sp.group(1)), mass=float(mass.group(1)))
    rob = re.search(r"= \*\*([0-9.]+) kg\*\*", txt)
    out["robot"] = float(rob.group(1)) if rob else 4.28
    return out


def main():
    sg, og = snow_groups(), original_groups()
    pr = json.load(open(os.path.join(HERE, "out", "print.json")))
    gj = json.load(open(os.path.join(HERE, "out", "gait.json")))
    og_g = orig_gait()
    A_ball, A_shoe = math.pi * 10 ** 2, SG.AREA
    W = P.ROBOT_MASS_SNOW * G
    L = ["# COMPARISON — Leg Day (original, `../`) vs snow leg (`snow_leg/`)\n",
         "Generated by `analysis/compare.py` from the analysis outputs. Original-leg loads are its own gait.md (robot "
         f"{og_g['robot']:.2f} kg, competition stance); snow-leg loads are its snow-mode gait (robot {P.ROBOT_MASS_SNOW} kg). "
         "Foot loads and sinkage use the snow robot (4.5 kg) for both feet so they compare like for like.\n",
         "## Mass (slicer filament + hardware list)\n",
         "| | original | snow | change |\n|---|---|---|---|"]
    for k, lab in (("foot", "foot group (below the ankle / ball foot)"), ("shank", "shank + knee pulley"), ("thigh", "thigh"),
                   ("swinging", "**swinging leg**"), ("hip_module", "hip module incl. 2 motors"), ("whole", "**whole leg incl. 3 motors**")):
        L.append(f"| {lab} | {og[k]:.0f} g | {sg[k]:.0f} g | {sg[k]-og[k]:+.0f} g |")
    L.append("\n## Foot, load and sinkage (4.5 kg robot)\n")
    L.append("| | original ball Ø20 | snowshoe 120 × 80 |\n|---|---|---|")
    L.append(f"| contact area | {A_ball/100:.2f} cm² | {A_shoe/100:.1f} cm² |")
    for case, n in (("static", 4), ("walk", 3), ("trot", 2)):
        F = W / n
        L.append(f"| foot load, {case} | {F/G*1000/(A_ball/100):.0f} g/cm² | {F/G*1000/(A_shoe/100):.1f} g/cm² |")
    F_w = W / 3
    for s in list(BEKKER) + list(PRESTON):
        zb = sink(F_w, A_ball * 1e-6, 0.010, s) * 100
        zs = sink(F_w, A_shoe * 1e-6, P.FOOT_W / 1000, s) * 100
        L.append(f"| predicted sinkage, walk, {s} | {zb:.1f} cm | {zs:.1f} cm |")
    L.append("\n## Joint ranges\n")
    L.append("| joint | original | snow |\n|---|---|---|")
    L.append("| ab/ad | ±45° firmware, no physical stop (free ±98°) | ±45° firmware, **spine stop blocks at ±47.5°** |")
    L.append("| hip | ±100° firmware, bridge stop ±107° | ±100° firmware, C-frame column stop ±107° |")
    L.append(f"| knee | 15–150° firmware, no physical stop | **{P.Q2_LIM[0]:.0f}–{P.Q2_LIM[1]:.0f}°** firmware (the snowshoe reaches the hip pod beyond ~140°), "
             f"**steel stop posts at 13° / 139°** |")
    L.append(f"| ankle | none (rigid ball) | passive pitch {SG.ALPHA_MIN:.1f}…{SG.ALPHA_MAX:.1f}° (stance range ±15°), cross-bolt stops, centring springs |")
    L.append("\n## Belt and motor loads (each leg's own gait; limits: motors 1.3 Nm rated / 4.1 peak, belt 60 N continuous / 120 N peak)\n")
    L.append("| gait | leg | speed m/s | hip motor Nm | knee motor Nm | ab/ad Nm | belt N | max robot mass at 60 N belt |\n|---|---|---|---|---|---|---|---|")
    for gait in ("walk", "trot"):
        o = og_g[gait]
        s = gj[f"snow_{gait}"]
        L.append(f"| {gait} | original ({og_g['robot']:.2f} kg) | {o['speed']:.2f} | {o['hip']:.2f} | {o['knee']:.2f} | {o['abad']:.2f} | {o['belt']:.0f} | {o['mass']:.1f} kg |")
        L.append(f"| {gait} | snow ({P.ROBOT_MASS_SNOW} kg, snow stance) | {s['speed']:.2f} | {s['t_hip']:.2f} | {s['t_knee']:.2f} | {s['t_abad']:.2f} | "
                 f"{s['belt']:.0f} | {s['mass_belt_cont']:.1f} kg |")
    L.append("\n## Build\n")
    so, oo = pr["snow"], pr["original"]

    def tot(d):
        return sum(v["minutes"] for k, v in d.items() if k != "coupon_fit_test") / 60, \
            sum((v["grams"] or 0) for k, v in d.items() if k != "coupon_fit_test")
    ts, gs_ = tot(so)
    to, go = tot(oo)
    L.append("| | original | snow |\n|---|---|---|")
    L.append(f"| printed parts (excl. coupon) | {len(oo) - 1} | {len(so) - 1} |")
    L.append(f"| print time (PrusaSlicer, excl. coupon) | {to:.1f} h | {ts:.1f} h |")
    L.append(f"| filament (excl. coupon) | {go:.0f} g | {gs_:.0f} g |")
    L.append("| heat-set inserts | 4 (M3, rig plate only) | 31 (23 × M3 + 8 × M5) |")
    warn_o = [k for k, v in oo.items() if v["slicer_warnings"]]
    warn_s = [k for k, v in so.items() if v["slicer_warnings"]]
    L.append(f"| parts with PrusaSlicer stability warnings, supports off | {len(warn_o)} ({', '.join(warn_o)}) | {len(warn_s)} |")
    L.append("| belt channel sealed | no (truss holes into the channel) | yes (no holes, seam lip, 2RS bearings, fender-washed idler slot) |")
    L.append("\n## Side-by-side renders (same SolidWorks camera views)\n")
    for tag in ("trimetric", "side", "front", "bottom"):
        L.append(f"![{tag}](docs/renders/compare_{tag}.png)\n")
    L.append("`compare_legs.SLDASM` holds both legs 250 mm apart (the original referenced read-only from `../cad/parts/`).\n")
    txt = "\n".join(L)
    open(os.path.join(ROOT, "COMPARISON.md"), "w", encoding="utf-8").write(txt)
    print(txt)


if __name__ == "__main__":
    main()
