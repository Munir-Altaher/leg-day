    w("## Sanity anchors (brief 4.4, 4.5)\n")
    w("| knee pulley | N | max vertical F (belt 120 N, rated torque) |\n|---|---|---|")
    for T in (20, 40, 48, 60):
        N = T / 20
        rk = T * 2 / math.pi / 2000
        F, _ = max_vertical_force(0.13, 0.13, 0.04, N, rk, q2_deg=90)
        w(f"| {T}T | {N:.1f} | {F:.1f} N |")
    q = np.array([0, -math.pi / 4, math.pi / 2])
    t0 = joint_torques(q, np.array([0, -20, 0]), 0.13, 0.13, 0.04)[0]
    t0p = joint_torques(q, np.array([0, -20, 2]), 0.13, 0.13, 0.04)[0]
    t0m = joint_torques(q, np.array([0, -20, -2]), 0.13, 0.13, 0.04)[0]
    w(f"\nAb/ad, l=40 mm, 20 N vertical: |tau0| = {abs(t0):.2f} Nm; with +/-2 N lateral: {abs(t0p):.2f} / {abs(t0m):.2f} Nm\n")

    # ---- design point
    N = P.N_RATIO
    r_knee = P.PD_KNEE / 2000
    H = P.STANCE_FRAC * (L1 + L2)
    w(f"## Design point: L1 = L2 = {P.L1:.0f} mm, {P.HIP_TEETH}T:{P.KNEE_TEETH}T (N = {N:.2f}), l = {P.L_ABAD:.1f} mm\n")
    w(f"Nominal stance height STANCE_FRAC(L1+L2) = {H*1000:.0f} mm\n")
    Fmax, qn = max_vertical_force(L1, L2, l, N, r_knee, height=H, lat_frac=0.1, T_lim=P.BELT_T_CONT)
    Fpk, _ = max_vertical_force(L1, L2, l, N, r_knee, height=H, lat_frac=0.1, tau_lim=P.TAU_PEAK, T_lim=P.BELT_T_PEAK)
    w(f"- Nominal stance joint angles: q1 = {math.degrees(qn[1]):.1f} deg, q2 = {math.degrees(qn[2]):.1f} deg")
    w(f"- Continuous capability (+/-10% lateral, motors <= rated, belt <= {P.BELT_T_CONT:.0f} N): **{Fmax:.1f} N** vertical (target >= 15 N)")
    w(f"- Peak capability (motors <= peak, belt <= {P.BELT_T_PEAK:.0f} N): **{Fpk:.1f} N** vertical\n")

    Fd = 15.0
    F = np.array([0, -Fd, 0.1 * Fd])
    tq = joint_torques(qn, F, L1, L2, l)
    tm = motor_torques(tq, N)
    T = belt_tension(tq[2], r_knee)
    w(f"Static load case: {Fd:.0f} N down + {0.1*Fd:.1f} N lateral at nominal stance")
    w(f"- joint torques tau_q = [{tq[0]:.3f}, {tq[1]:.3f}, {tq[2]:.3f}] Nm")
    w(f"- motor torques [abad, hip, knee] = [{tm[0]:.3f}, {tm[1]:.3f}, {tm[2]:.3f}] Nm (rated 1.3)")
    w(f"- belt effective tension = {T:.1f} N (continuous limit {P.BELT_T_CONT:.0f} N)\n")

    tk_lim = P.BELT_T_PEAK * r_hip
    w("## Firmware limits\n")
    w(f"- knee motor torque limit = T_peak x r_hip = {P.BELT_T_PEAK:.0f} N x {r_hip*1000:.2f} mm = **{tk_lim:.2f} Nm**")
    w(f"- hip motor: 4.1 Nm peak, set 2.5 Nm (structure SF>=2, see skeleton check); ab/ad: 2.5 Nm")
    w(f"- knee joint torque available at belt peak: {P.BELT_T_PEAK * r_knee:.2f} Nm\n")

    # ---- belt length
    C = L1 * 1000
    D1, D2 = P.PD_HIP, P.PD_KNEE
    Lb = 2 * C + math.pi * (D1 + D2) / 2 + (D2 - D1) ** 2 / (4 * C)
    w("## Belt\n")
    w(f"- open-belt length at C = {C:.0f} mm: {Lb:.1f} mm -> {2*math.ceil(Lb/2):.0f} mm ({math.ceil(Lb/2):.0f} teeth) + idler take-up; "
      f"with 2 x 15 mm clamp overlap cut {2*math.ceil(Lb/2)+30:.0f} mm (supplied {P.BELT_SUPPLIED:.0f} mm ASSUMED)")
