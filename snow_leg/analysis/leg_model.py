# ------------------------------------------------------------------ kinematics (metres, radians)
def fk(q, L1, L2, l):
    q0, q1, q2 = q
    xa = L1 * math.sin(q1) + L2 * math.sin(q1 + q2)
    ya = -L1 * math.cos(q1) - L2 * math.cos(q1 + q2)
    return np.array([xa, ya * math.cos(q0) - l * math.sin(q0), ya * math.sin(q0) + l * math.cos(q0)])


def ik(p, L1, L2, l):
    x, y, z = p
    D = math.sqrt(max(y * y + z * z - l * l, 0.0))
    q0 = math.atan2(z, y) - math.atan2(l, -D)
    q0 = (q0 + math.pi) % (2 * math.pi) - math.pi
    c = (x * x + D * D - L1 * L1 - L2 * L2) / (2 * L1 * L2)
    q2 = math.acos(max(-1.0, min(1.0, c)))
    q1 = math.atan2(x, D) - math.atan2(L2 * math.sin(q2), L1 + L2 * math.cos(q2))
    return np.array([q0, q1, q2])


def jac(q, L1, L2, l, h=1e-7):
    J = np.zeros((3, 3))
    for i in range(3):
        dq = np.zeros(3)
        dq[i] = h
        J[:, i] = (fk(q + dq, L1, L2, l) - fk(q - dq, L1, L2, l)) / (2 * h)
    return J


def joint_torques(q, F, L1, L2, l):
    """tau = J^T F, F = force foot applies to ground. Returns joint torques for
    the joint to *hold* that force (sign: torque the joint must exert)."""
    return jac(q, L1, L2, l).T @ F


def motor_torques(tau_q, N):
    """Belt coupling (brief 4.3): th_k = q1 + N q2."""
    t0, t1, t2 = tau_q
    tk = t2 / N
    th = t1 - tk
    return np.array([t0, th, tk])


def belt_tension(tau_q2, r_knee):
    return abs(tau_q2) / r_knee


def virtual_work_check(N=2.4):
    # motor angle map th = A q ; tau_q = A^T tau_m must hold
    A = np.array([[1, 0, 0], [0, 1, 0], [0, 1, N]], float)
    tm = np.array([0.3, -0.7, 0.4])
    tq = A.T @ tm
    back = motor_torques(tq, N)
    return np.allclose(back, tm)


def roundtrip_test(L1, L2, l, n=4000, seed=1):
    rng = np.random.default_rng(seed)
    worst = 0.0
    for _ in range(n):
        q = np.array([rng.uniform(*np.radians(P.Q0_LIM)),
                      rng.uniform(-math.radians(80), math.radians(80)),
                      rng.uniform(*np.radians(P.Q2_LIM))])
        p = fk(q, L1, L2, l)
        if fk(q, L1, L2, l)[1] * math.cos(q[0]) + 0 > 0:
            pass
        # branch valid while foot is below the hip-pitch axis (y_A < 0)
        ya = -L1 * math.cos(q[1]) - L2 * math.cos(q[1] + q[2])
        if ya >= -1e-3:
            continue
        q2 = ik(p, L1, L2, l)
        worst = max(worst, np.max(np.abs(q2 - q)))
    return worst


# ------------------------------------------------------------------ capability at a pose
def max_vertical_force(L1, L2, l, N, r_knee, x=0.0, height=None, lat_frac=0.0,
                       tau_lim=P.TAU_RATED, T_lim=P.BELT_T_PEAK, q2_deg=None):
    if q2_deg is not None:
        q = np.array([0.0, -math.radians(q2_deg) / 2, math.radians(q2_deg)])
    else:
        q = ik(np.array([x, -height, l]), L1, L2, l)
    best = 1e9
    for s in (1, -1) if lat_frac else (1,):
        F = np.array([0.0, -1.0, s * lat_frac])        # foot pushes down on ground
        tm = motor_torques(joint_torques(q, F, L1, L2, l), N)
        T = belt_tension(joint_torques(q, F, L1, L2, l)[2], r_knee)
        lim = min([tau_lim / abs(t) for t in tm if abs(t) > 1e-9] + ([T_lim / T] if T > 1e-9 else []))
        best = min(best, lim)
    return best, q


